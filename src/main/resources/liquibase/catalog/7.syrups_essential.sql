-- 295 Сахарный, 133 Медовый, 77 Гренадин, 75 маракуйи, 121 Ванильный, 99 Миндальный, 43 Малиновый, 446 агавы,
-- 448 Клубничный, 450 Имбирный, 445 корицы, 134 Кленовый, 447 Карамельный, 452 Черносмородиновый, 453 Яблочный жёлтый,
-- 196 Кокосовый, 123 розы, 463 манго, 454 лимонника, 462 личи.
UPDATE drink_me_bot.goods
SET is_essential = TRUE
WHERE id IN (295, 133, 77, 75, 121, 99, 43, 446, 448, 450, 445, 134, 447, 452, 453, 196, 123, 463, 454, 462);

INSERT INTO drink_me_bot.goods_category (goods_id, category)
SELECT id, 'SYRUP'
FROM drink_me_bot.goods
WHERE id IN (295, 133, 77, 75, 121, 99, 43, 446, 448, 450, 445, 134, 447, 452, 453, 196, 123, 463, 454, 462)
ON CONFLICT (goods_id) DO UPDATE SET category = EXCLUDED.category;
